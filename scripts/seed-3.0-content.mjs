async function main() {
  console.log("🌱 Digital Garden 3.0 — Seeding 52 entries...\n");

  const entries = await prisma.entry.findMany({
    select: { id: true, title: true, slug: true },
    orderBy: { createdAt: "asc" },
  });

  console.log(`Found ${entries.length} entries in database.\n`);

  let updated = 0;
  let skipped = 0;

  for (const entry of entries) {
    const builder = E[entry.title];
    if (!builder) {
      console.log(`⚠️  No content defined for: "${entry.title}" — skipping`);
      skipped++;
      continue;
    }

    const content = builder();
    const contentMd = extractMarkdown(content);

    await prisma.entry.update({
      where: { id: entry.id },
      data: {
        content,
        contentMd,
        excerpt: contentMd.slice(0, 200).replace(/[#*`\[\]()>\\\-_~]/g, "").trim(),
      },
    });

    updated++;
    console.log(`✅ [${updated}/${entries.length}] ${entry.title}`);
  }

  console.log(`\n🎉 Done! Updated ${updated} entries. Skipped ${skipped}.`);
  await prisma.$disconnect();
}

// Simple Markdown extraction for excerpt/contentMd
function extractMarkdown(json) {
  const doc = JSON.parse(json);
  const lines = [];
  function walk(node) {
    if (typeof node === "string") { lines.push(node); return; }
    if (!node || typeof node !== "object") return;
    if (node.type === "text") { lines.push(node.text || ""); return; }
    if (node.type === "heading") { lines.push("#".repeat(node.attrs?.level || 1) + " "); walk(node.content); lines.push("\n\n"); return; }
    if (node.type === "horizontalRule") { lines.push("---\n\n"); return; }
    if (Array.isArray(node.content)) node.content.forEach(walk);
    if (node.type === "paragraph") lines.push("\n\n");
  }
  walk(doc);
  return lines.join("").replace(/\n{3,}/g, "\n\n").trim();
}

